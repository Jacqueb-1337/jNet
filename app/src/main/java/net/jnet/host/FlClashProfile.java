package net.jnet.host;

/**
 * Generates an ordinary Mihomo profile. Client VPN/TUN activation is intentionally
 * not part of the profile: FlClash owns that setting and Android requires consent.
 */
final class FlClashProfile {
    private FlClashProfile() {}

    static String yaml(String host, int port, String password) {
        if (!host.matches("[0-9]{1,3}(\\.[0-9]{1,3}){3}"))
            throw new IllegalArgumentException("Expected a numeric IPv4 jNet endpoint.");
        if (port < 1 || port > 65535)
            throw new IllegalArgumentException("Invalid SOCKS5 port.");
        StringBuilder yaml = new StringBuilder();
        yaml.append("# jNet connection, generated by your host phone.\n")
            .append("# Enable VPN (Android) or TUN (desktop) in FlClash after importing.\n")
            .append("mode: rule\n")
            .append("log-level: warning\n")
            .append("allow-lan: false\n")
            .append("proxies:\n")
            .append("  - name: \"jNet SOCKS5\"\n")
            .append("    type: socks5\n")
            .append("    server: ").append(quoted(host)).append("\n")
            .append("    port: ").append(port).append("\n")
            .append("    udp: true\n");
        if (password != null && !password.isEmpty()) {
            yaml.append("    username: \"jnet\"\n")
                .append("    password: ").append(quoted(password)).append("\n");
        }
        yaml.append("proxy-groups:\n")
            .append("  - name: jNet\n")
            .append("    type: select\n")
            .append("    proxies:\n")
            .append("      - \"jNet SOCKS5\"\n")
            .append("dns:\n")
            .append("  enable: true\n")
            .append("  ipv6: false\n")
            .append("  enhanced-mode: fake-ip\n")
            .append("  nameserver:\n")
            .append("    - https://1.1.1.1/dns-query#jNet\n")
            .append("    - https://8.8.8.8/dns-query#jNet\n")
            .append("rules:\n")
            .append("  - IP-CIDR,").append(host).append("/32,DIRECT,no-resolve\n")
            .append("  - IP-CIDR,10.0.0.0/8,DIRECT,no-resolve\n")
            .append("  - IP-CIDR,172.16.0.0/12,DIRECT,no-resolve\n")
            .append("  - IP-CIDR,192.168.0.0/16,DIRECT,no-resolve\n")
            .append("  - MATCH,jNet\n");
        return yaml.toString();
    }

    private static String quoted(String value) {
        StringBuilder out = new StringBuilder("\"");
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '\\' -> out.append("\\\\");
                case '"' -> out.append("\\\"");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case '\t' -> out.append("\\t");
                default -> {
                    if (c < 0x20 || c == 0x7f)
                        out.append(String.format(java.util.Locale.ROOT, "\\u%04x", (int)c));
                    else out.append(c);
                }
            }
        }
        return out.append('"').toString();
    }
}
